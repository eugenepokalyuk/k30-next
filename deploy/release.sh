#!/usr/bin/env bash
# Перевод витрины на свежий релиз. Запускается на сервере из GitHub Actions:
# файлы к этому моменту уже залиты rsync-ом в staging, здесь только фиксация.
# Первым аргументом — имя релиза (SHA коммита).
set -euo pipefail

REL="${1:?не передано имя релиза}"
cd /srv/k30-next

# cp -al вместо копирования: релиз — это жёсткие ссылки на те же файлы, места
# не занимает и делается мгновенно. rsync пишет через временный файл с
# переименованием, поэтому следующая выкатка не протечёт в старые релизы через
# общий inode
rm -rf "releases/$REL"
cp -al staging "releases/$REL"

# Переименование симлинка атомарно: запрос попадает либо целиком в старый
# релиз, либо целиком в новый, промежуточного состояния нет
ln -sfn "releases/$REL" current.new
mv -T current.new current

# Держим три последних релиза — на откат хватает, а диска на сервере 8 ГБ
ls -1dt releases/*/ | tail -n +4 | xargs -r rm -rf

echo "==> выкачен $(readlink current)"
